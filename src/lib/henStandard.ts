function interpolate(table: HenStandardPoint[], week: number, key: keyof HenStandardPoint): number | null {
  if (table.length === 0) return null;
  if (week <= table[0].week) return table[0][key] as number;
  if (week >= table[table.length - 1].week) return table[table.length - 1][key] as number;
  for (let i = 0; i < table.length - 1; i++) {
    const a = table[i], b = table[i + 1];
    if (week >= a.week && week <= b.week) {
      const t = (week - a.week) / (b.week - a.week);
      return (a[key] as number) + t * ((b[key] as number) - (a[key] as number));
    }
  }
  return null;
}

export function standardCumulativeMortalityForWeek(week: number): number | null {
  return interpolate(HEN_STANDARD, week, 'cumulativeMortality');
}

export function standardHdepForWeek(week: number): number | null {
  return interpolate(HEN_STANDARD, week, 'hdep');
}
